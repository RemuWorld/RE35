'use strict';
const assert = require('node:assert/strict');
const { createEditorInputActions, capture } = require('../editor-input-actions');
const { fixture } = require('./editor-fixture');
async function run() {
  let checks = 0; const eq = (a, b, label) => { assert.deepEqual(a, b, label); ++checks; };
  const f = fixture(), actions = createEditorInputActions({ vscode: f.vscode });
  const call = (id, args = {}, frame = {}) => actions['editor.' + id](args, frame);
  f.select(1, 5); await call('select_word'); eq([f.editor.selection.start.character, f.editor.selection.end.character], [3, 9], 'Use the document language word range, including Straße');
  const result = await call('uppercase_selection'); eq(f.doc.lineAt(1).text, '한글 STRASSE 😀 last'); eq(result.sourceVersion, 2); eq(result.mode, 'editor');
  eq(f.edits.length, 1); eq(f.edits[0].options, { undoStopBefore: true, undoStopAfter: true });
  eq([f.editor.selection.start.character, f.editor.selection.end.character], [3, 10], 'Unicode uppercase expansion preserves the transformed selection');
  await call('uppercase_selection'); eq(f.edits.length, 1, 'A no-op creates no undo edit');
  f.select(0, 0); await call('move_words', { count: '2' }); eq(f.calls, ['cursorWordRight', 'cursorWordRight']); eq(f.editor.selection.active.character, 7);
  f.select(0, 0); await call('delete_lines', { count: 1 }); eq(f.doc.getText(), '한글 STRASSE 😀 last\nfinal'); eq(f.edits.length, 2);
  f.select(1, 0); await call('delete_lines'); eq(f.doc.getText(), '한글 STRASSE 😀 last', 'Deleting the final line consumes its line break');
  const reversed = fixture('aßc 😀'), reverseActions = createEditorInputActions({ vscode: reversed.vscode }); reversed.select(0, 3, 0, 0);
  await reverseActions['editor.uppercase_selection']({}, {}); eq(reversed.doc.getText(), 'ASSC 😀'); eq([reversed.editor.selection.anchor.character, reversed.editor.selection.active.character], [4, 0]);
  for (const value of [0, -1, '01', '1e2', 1001, true]) { await assert.rejects(call('move_words', { count: value }), /Count/); ++checks; }
  await assert.rejects(call('select_word', { surprise: 1 }), /no arguments/); ++checks;
  f.select(0, 2); await assert.rejects(call('select_word'), /no VS Code language word/); ++checks;
  f.select(0, 0); await assert.rejects(call('uppercase_selection'), /nonempty/); ++checks;
  const old = capture(f.vscode); f.type('!'); await assert.rejects(call('delete_lines', {}, { source: { editor: f.editor, version: old.version } }), /source changed/); ++checks;
  const changedSelection = capture(f.vscode); f.select(0, 1); await assert.rejects(call('delete_lines', {}, { editingSource: changedSelection }), /selection changed/); ++checks;
  const native = createEditorInputActions({ vscode: f.vscode, engineAvailable: () => ({ available: false, reason: 'Disable vscode-neovim before editor activation' }) });
  await assert.rejects(native['editor.move_words']({}, {}), /Disable vscode-neovim/); ++checks;
  const unicode = fixture('😀 word'), unicodeActions = createEditorInputActions({ vscode: unicode.vscode }); unicode.select(0, 1);
  await assert.rejects(unicodeActions['editor.uppercase_selection']({}, {}), /splits a Unicode/); ++checks;
  const cancelled = fixture('word'), cancellationActions = createEditorInputActions({ vscode: cancelled.vscode }); cancelled.select(0, 0, 0, 4);
  const controller = new AbortController(); controller.abort(); await assert.rejects(cancellationActions['editor.uppercase_selection']({}, { signal: controller.signal }), /changed before/); ++checks; eq(cancelled.edits.length, 0);
  const race = fixture('word'), raceActions = createEditorInputActions({ vscode: race.vscode }); race.select(0, 0, 0, 4);
  race.editHook(async stage => { if (stage === 'after') race.type(' user'); });
  await assert.rejects(raceActions['editor.uppercase_selection']({}, {}), /beyond the requested edit/); ++checks; eq(race.doc.getText(), 'WORD user', 'A concurrent user edit is preserved and not replayed');
  const lost = fixture('word'), lostActions = createEditorInputActions({ vscode: lost.vscode }); lost.select(0, 0, 0, 4);
  lost.editHook(async stage => { if (stage === 'after') lost.focus(false); });
  await assert.rejects(lostActions['editor.uppercase_selection']({}, {}), /lost window focus/); ++checks; eq(lost.doc.getText(), 'WORD');
  const chain = fixture('first\r\n한글 Straße 😀\r\nlast'), chainActions = createEditorInputActions({ vscode: chain.vscode });
  chain.select(1, 4);
  await chainActions['editor.select_line']({}, {});
  eq(chain.doc.getText(chain.editor.selection), '한글 Straße 😀\r\n');
  await chainActions['editor.uppercase_selection']({}, {});
  eq(chain.doc.getText(), 'first\r\n한글 STRASSE 😀\r\nlast');
  await chainActions['editor.document_start']({}, {});
  eq([chain.editor.selection.anchor.line, chain.editor.selection.active.character], [0, 0]);
  await chainActions['editor.select_line']({}, {});
  await chainActions['editor.extend_to_end']({}, {});
  eq(chain.doc.getText(chain.editor.selection), chain.doc.getText());
  eq(chain.doc.version, 2, 'Selection-only commands do not edit or add Undo entries');
  chain.select(2, 1); await chainActions['editor.select_line']({}, {});
  eq(chain.doc.getText(chain.editor.selection), 'last');
  const blank = fixture(''), blankActions = createEditorInputActions({ vscode: blank.vscode });
  eq((await blankActions['editor.select_line']({}, {})).changed, false);
  eq((await blankActions['editor.extend_to_end']({}, {})).changed, false);
  await assert.rejects(chainActions['editor.select_line']({ count: 2 }, {}), /no arguments/); ++checks;
  const delayed = fixture('first\nsecond'), acknowledgements = [];
  delayed.selectionHook(value => acknowledgements.push(value));
  const delayedActions = createEditorInputActions({ vscode: delayed.vscode });
  let observed = false;
  const selecting = delayedActions['editor.select_line']({}, {}).then(value => { observed = true; return value; });
  await Promise.resolve();
  eq(observed, false, 'The setter local echo is not native completion');
  eq(delayed.listenerCount('selection'), 1);
  acknowledgements.shift().emit(3); eq((await selecting).observed, true);
  eq(delayed.listenerCount('selection'), 0, 'The acknowledgement releases its listener');
  eq(delayed.doc.version, 1);
  const stopped = fixture('first\nsecond'), stoppedAcks = [], stop = new AbortController();
  stopped.selectionHook(value => stoppedAcks.push(value));
  const stoppedActions = createEditorInputActions({ vscode: stopped.vscode });
  let settled = false;
  const stopping = stoppedActions['editor.select_line']({}, { stopSignal: stop.signal }).finally(() => { settled = true; });
  stop.abort(); await Promise.resolve(); eq(settled, false, 'Cancellation drains a submitted setter before releasing input');
  stoppedAcks.shift().emit(3);
  await assert.rejects(stopping, cause => cause.effects === 'observed-cancelled'); ++checks;
  eq(stopped.listenerCount('selection'), 0);
  const silent = fixture('first\nsecond'); silent.selectionHook(() => {});
  const silentActions = createEditorInputActions({ vscode: silent.vscode, selectionTimeout: 10 });
  await assert.rejects(silentActions['editor.select_line']({}, {}), cause => cause.code === 'RE35_SELECTION_UNCONFIRMED'); ++checks;
  eq(silent.listenerCount('selection'), 0, 'Missing acknowledgement remains uncertain and releases observation resources');
  return { checks };
}
if (require.main === module) run().then(value => console.log(JSON.stringify(value))).catch(cause => { console.error(cause); process.exitCode = 1; });
module.exports = { run };
